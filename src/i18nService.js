function translateMoneyManagerError(message, lang = 'bn') {
  const raw = String(message || '').trim();
  if (!raw) return '';
  const key = MONEY_MANAGER_ERROR_KEYS[raw];
  if (key) return t(key, lang);
  const containsBangla = /[\u0980-\u09FF]/.test(raw);
  if (lang === 'en' && containsBangla) return t('mm_error_generic', lang);
  if (lang === 'bn' && !containsBangla) return t('mm_error_generic', lang);
  return raw;
}

function t(key, lang = 'bn', params = {}) {
  const dictionary = STRINGS[lang] || STRINGS.bn;
  let text = dictionary[key] || STRINGS.bn[key] || key;
  if (params && typeof params === 'object') {
    Object.keys(params).forEach((k) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(params[k]));
    });
  }
  return text;
}

