function removeRepeatedTrailingCopy(content) {
  const tokens = [...String(content).matchAll(/\S+/g)];
  const words = tokens.map((match) => match[0]);
  for (let repeatedLength = Math.floor(words.length / 2); repeatedLength > 0; repeatedLength--) {
    const suffixStart = words.length - repeatedLength;
    const previousStart = suffixStart - repeatedLength;
    if (previousStart >= 0
      && words.slice(previousStart, suffixStart).join(' ') === words.slice(suffixStart).join(' ')) {
      return String(content).slice(0, tokens[suffixStart].index).trimEnd();
    }
  }
  return String(content);
}

function translateMoneyManagerDefaultValue(kind, id, value, lang = 'bn', field = '') {
  const source = String(value == null ? '' : value);
  const key = kind === 'transaction' ? `${id}_${field}` : id;
  const entry = DEFAULT_MONEY_MANAGER_TRANSLATIONS[kind]?.[key];
  if (!entry || (source !== entry[0] && source !== entry[2])) return source;
  return lang === 'en' ? entry[1] : entry[0];
}

function translateStaticText(text, lang = 'bn') {
  const source = String(text == null ? '' : text);
  if (!source) return source;
  const leading = (source.match(/^\s*/) || [''])[0];
  const trailing = (source.match(/\s*$/) || [''])[0];
  const contentEnd = trailing.length ? source.length - trailing.length : source.length;
  const content = removeRepeatedTrailingCopy(source.slice(leading.length, contentEnd));
  if (!content) return source;
  const normalizedContent = content.replace(/\s+/g, ' ').trim();
  if (lang !== 'en') return `${leading}${content}${trailing}`;
  let translated = APP_STATIC_TEXT_EN[content] || APP_STATIC_TEXT_EN[normalizedContent]
    || STATIC_DICTIONARY_EN[content] || STATIC_DICTIONARY_EN[normalizedContent];
  if (!translated) {
    translated = content.replace(/[০-৯]/g, (digit) => String('০১২৩৪৫৬৭৮৯'.indexOf(digit)));
  }
  return `${leading}${translated}${trailing}`;
}

